import type { OHLCDataPoint } from "./bklit/candlestick-chart";
import type { ReportMonth } from "./data";

// Daily sample prices. Each session opens at the previous session's close.
type DailyQuote = [high: number, low: number, close: number];

function monthOfPrices(month: ReportMonth, openingPrice: number, quotes: DailyQuote[]): OHLCDataPoint[] {
  return quotes.map(([high, low, close], index) => ({
    date: new Date(`${month}-${String(index + 1).padStart(2, "0")}T12:00:00Z`),
    open: index === 0 ? openingPrice : quotes[index - 1][2],
    high,
    low,
    close,
  }));
}

